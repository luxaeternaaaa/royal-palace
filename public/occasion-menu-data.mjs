function newYear(hall, price, variant, sourceId) {
  const cold = [dish('Рыбное ассорти', 'Лосось, эсколар, угорь'), dish('Ассорти «Казахстан»', 'Казы, шужык, жая'), dish('Разносолы по-домашнему или кавказская закуска')];
  cold.push(variant === 3 && hall !== 'small'
    ? dish('Капрезе', 'Мусс из страчателлы с томатами черри') : ballotine);
  const salads = variant === 1
    ? [dish('Классический оливье с индейкой'), dish('Сельдь под шубой'), royal, pumpkin, salmonSalad]
    : variant === 2
      ? [dish('Классический оливье с кониной'), dish('Сельдь под шубой'), burrata, chickenSalad, duckSalad]
      : [dish('Классический оливье с кониной'), dish('Сельдь под шубой'), burrata, royal, nicoise];
  const firstHot = variant === 1
    ? 'Бешбармак (нарезное мясо) или томлёные говяжьи рёбра в собственном соку с пюре из тыквы'
    : 'Бешбармак (нарезное мясо) или медальоны из говядины с соусом демиглас и дроблёным картофелем';
  const included = hall === 'main'
    ? 'Включены звук, 4 LED-экрана, свет, фуршет и оформление зала.'
    : hall === 'middle'
      ? 'Включены звук, 5 LED-экранов, свет, фуршет и оформление зала.'
      : 'Включены звук, LED-экран, свет, фуршет и оформление зала.';
  return {
    id: `newyear-${hall}-${price}`, occasion: 'newyear', hall, paper: `newyear-${hall}`, sourceId,
    title: `Новогоднее меню · ${hallNames[hall]}`, price, guests: guests[hall], days: '', seating: 'Посадка от 12 персон',
    servicesIncluded: true, serviceTerms: included, extras: [],
    columns: [
      [section('Холодные закуски', cold), section('Салаты', salads)],
      [section('Выпечка', [dish(variant === 1 ? 'Ассорти булочек и гриссини' : 'Хлеб и гриссини'), dish('Бауырсаки')]),
        section('Горячая закуска', [dish(variant === 1 ? 'Самса с говядиной' : 'Самса с мясом')]),
        section('Основное блюдо', [dish(firstHot)]), section('Второе горячее', [dish([pikePerch, salmon, halibut][variant - 1])]), desserts, drinks],
    ],
    notes: ['Напитки — без ограничений.', included,
      ...(hall === 'middle' && variant === 2 ? ['Медальоны подаются индивидуально.'] : [])],
  };
}

